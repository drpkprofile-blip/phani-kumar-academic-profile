begin;

create table public.patents (
  id integer generated by default as identity primary key,
  application_number text not null unique check (application_number ~ '[^[:space:]]'),
  filing_date date not null,
  publication_date date not null check (publication_date >= filing_date),
  title text not null check (title ~ '[^[:space:]]'),
  journal_number text not null check (journal_number ~ '[^[:space:]]'),
  page_number text not null check (page_number ~ '[^[:space:]]'),
  proof_url text check (proof_url is null or (proof_url ~* '^https?://[^[:space:]]+$' and proof_url !~* '^https?://[^/]*@')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger patents_timestamps
before insert or update on public.patents
for each row execute function private.set_record_timestamps();

