create function public.admin_save_patent(
  p_id integer default null,
  p_patent jsonb default '{}'::jsonb,
  p_expected_updated_at timestamptz default null
) returns integer language plpgsql security invoker set search_path = '' as $$
declare
  saved_id integer;
  previous public.patents%rowtype;
  application_no text;
  filing_on date;
  published_on date;
  invention_title text;
  journal_no text;
  proof_link text;
begin
  if public.is_publications_admin() is distinct from true then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if jsonb_typeof(p_patent) is distinct from 'object'
    or (p_patent - array['application_number','filing_date','publication_date','title','journal_number','page_number','proof_url']::text[]) <> '{}'::jsonb then
    raise exception 'Patent object contains invalid fields' using errcode = '22023';
  end if;

  application_no := p_patent->>'application_number';
  invention_title := p_patent->>'title';
  journal_no := p_patent->>'journal_number';
  if coalesce(p_patent->>'page_number', '') !~ '[^[:space:]]' then
    raise exception 'A page number is required' using errcode = '22023';
  end if;
  if application_no is null or application_no !~ '[^[:space:]]'
    or invention_title is null or invention_title !~ '[^[:space:]]'
    or journal_no is null or journal_no !~ '[^[:space:]]' then
    raise exception 'Application number, title, and journal number are required' using errcode = '22023';
  end if;

  if coalesce(p_patent->>'filing_date', '') !~ '^\d{4}-\d{2}-\d{2}$'
    or coalesce(p_patent->>'publication_date', '') !~ '^\d{4}-\d{2}-\d{2}$' then
    raise exception 'Patent dates must use YYYY-MM-DD' using errcode = '22023';
  end if;
  filing_on := (p_patent->>'filing_date')::date;
  published_on := (p_patent->>'publication_date')::date;
  if published_on < filing_on then
    raise exception 'Publication date cannot precede filing date' using errcode = '22023';
  end if;

  proof_link := p_patent->>'proof_url';
  if proof_link is not null and btrim(proof_link) = '' then proof_link := null; end if;
  if proof_link is not null and (proof_link !~* '^https?://[^[:space:]]+$' or proof_link ~* '^https?://[^/]*@') then
    raise exception 'Proof link must be an HTTP or HTTPS URL' using errcode = '22023';
  end if;

  if p_id is null then
    insert into public.patents(application_number, filing_date, publication_date, title, journal_number, page_number, proof_url)
    values (application_no, filing_on, published_on, invention_title, journal_no, btrim(p_patent->>'page_number'), proof_link)
    returning id into saved_id;
  else
    select * into previous from public.patents where id = p_id and updated_at = p_expected_updated_at for update;
    if not found then
      raise exception 'Record changed or no longer exists; reload before saving' using errcode = 'P0001';
    end if;
    update public.patents set
      application_number = application_no,
      filing_date = filing_on,
      publication_date = published_on,
      title = invention_title,
      journal_number = journal_no,
      page_number = btrim(p_patent->>'page_number'),
      proof_url = proof_link
    where id = p_id returning id into saved_id;
  end if;
  return saved_id;
end;
$$;

create function public.admin_delete_patent(p_id integer, p_expected_updated_at timestamptz, p_confirmed boolean)
returns integer language plpgsql security invoker set search_path = '' as $$
declare deleted_id integer;
begin
  if public.is_publications_admin() is distinct from true then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if p_confirmed is distinct from true then
    raise exception 'Explicit deletion confirmation required' using errcode = '22023';
  end if;
  delete from public.patents where id = p_id and updated_at = p_expected_updated_at returning id into deleted_id;
  if deleted_id is null then
    raise exception 'Record changed or no longer exists; reload before deleting' using errcode = 'P0001';
  end if;
  return deleted_id;
end;
$$;

revoke all on function public.admin_save_patent(integer, jsonb, timestamptz) from public, anon, authenticated;
revoke all on function public.admin_delete_patent(integer, timestamptz, boolean) from public, anon, authenticated;
grant execute on function public.admin_save_patent(integer, jsonb, timestamptz) to authenticated;
grant execute on function public.admin_delete_patent(integer, timestamptz, boolean) to authenticated;

commit;
